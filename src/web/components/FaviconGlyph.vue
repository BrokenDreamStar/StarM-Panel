function shortName(raw: string): string {
  const s = raw.trim().toLowerCase()
  const withoutProvider = s.includes(':') ? (s.split(':').pop() ?? s) : s
  return withoutProvider.replace(/[-_\s]/g, '')
}

/** 名称 → 内置图标路径（做归一化查找） */
const LOOKUP: Map<string, string> = (() => {
  const map = new Map<string, string>()
  for (const [name, path] of Object.entries(GLYPHS)) {
    map.set(name.replace(/[-_\s]/g, ''), path)
  }
  return map
})()

/** 字符串 → 稳定 32 位哈希（FNV-1a），保证同一名称永远同一字形 */
function hashName(name: string): number {
  let h = 0x811c9dc5
  for (let i = 0; i < name.length; i++) {
    h ^= name.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return h >>> 0
}

/**
 * 几何回退字形：由哈希挑选几种基本图元组合。
 * 目的不是「好看」，而是**离线也有确定的视觉标识**且不同图标可区分。
 */
function fallbackPath(name: string): string {
  const h = hashName(name)
  const v = h % 6
  switch (v) {
    case 0:
      return 'M4 4h7v7H4zm9 0h7v7h-7zM4 13h7v7H4zm9 0h7v7h-7z'
    case 1:
      return 'M12 3l9 9-9 9-9-9z'
    case 2:
      return 'M12 3a9 9 0 1 1 0 18 9 9 0 0 1 0-18zm0 3a6 6 0 1 0 0 12 6 6 0 0 0 0-12z'
    case 3:
      return 'M4 5h16v4H4zm0 6h16v3H4zm0 5h10v3H4z'
    case 4:
      return 'M12 2l3 7 7 1-5 5 1 7-6-3.5L6 22l1-7-5-5 7-1z'
    default:
      return 'M5 3h9l5 5v13H5zm8 1.5V9h4.5z'
  }
}

const path = computed(() => LOOKUP.get(shortName(props.name)) ?? fallbackPath(props.name))
const isBuiltin = computed(() => LOOKUP.has(shortName(props.name)))
const size = computed(() =>
  typeof props.size === 'number' ? `${props.size}px` : props.size,
)

defineExpose({ isBuiltin })
</script>

